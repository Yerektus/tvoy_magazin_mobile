import 'package:flutter/foundation.dart';

/// Боевой бэкенд. С телефона приложение ходит сюда.
const String _production =
    'https://tvoymagazinapi-production.up.railway.app/api';

/// Локальный бэкенд для разработки в браузере.
const String _local = 'http://127.0.0.1:8000/api';

/// Адрес бэкенда.
///
/// На телефоне — боевой сервер: приложение там ставят, чтобы работать, а не
/// чтобы отлаживать, и компьютера рядом может не быть вовсе. В браузере —
/// локальный: там мы как раз и отлаживаем.
///
/// Любой из них перебивается при сборке:
///
/// ```
/// flutter run --dart-define=API_BASE_URL=http://127.0.0.1:8000/api
/// ```
///
/// Так на телефоне работают с местным бэкендом. Телефон до `127.0.0.1`
/// компьютера сам не дойдёт — нужен проброс порта по кабелю:
///
/// ```
/// adb reverse tcp:8000 tcp:8000
/// ```
///
/// Он живёт до отключения кабеля, после переподключения команду повторяют.
/// Django при этом может слушать только петлю, как и слушает: заголовок Host
/// остаётся `127.0.0.1`, и `ALLOWED_HOSTS` трогать не нужно.
///
/// Через Wi-Fi вместо этого подставляют IP компьютера (`ipconfig getifaddr
/// en0`), но тогда Django должен слушать не только петлю: `runserver
/// 0.0.0.0:8000` и этот IP в `DJANGO_ALLOWED_HOSTS`, иначе он ответит 400 даже
/// на дошедший запрос.
const String apiBaseUrl = String.fromEnvironment(
  'API_BASE_URL',
  defaultValue: kIsWeb ? _local : _production,
);
